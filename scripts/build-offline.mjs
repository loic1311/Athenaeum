// Run after building the catalog. Offline paths follow the same imports as the browser.
import { readFile, writeFile } from 'node:fs/promises';
import { catalogPacks } from '../academy/catalog-packs.js';
const root = new URL('../', import.meta.url);
const shell = await readFile(new URL('index.html',root),'utf8');
const local = (spec, base=root) => {
  const url = new URL(spec,base);
  return './' + url.pathname.slice(root.pathname.length) + url.search;
};
const initial = new Set(['./','./index.html','./leer/','./apps/paideia/index.html','./classic.html']);
for (const match of shell.matchAll(/(?:href|src)="(\.\/[^"#]+)"/g)) initial.add(match[1]);
const seen = new Set();
async function visit(spec, initialGraph) {
  const location = new URL(spec,root);
  if (initialGraph) initial.add(spec);
  if (seen.has(spec)) return;
  seen.add(spec);
  if (!location.pathname.endsWith('.js') && !location.pathname.endsWith('.mjs')) return;
  const code = await readFile(location,'utf8');
  if (location.pathname.includes('/vendor/')) return;
  for (const m of code.matchAll(/(?:from\s*|import\s*)['"](\.[./][^'"]+)['"]/g)) await visit(local(m[1],location),initialGraph);
}
for (const spec of [...initial]) await visit(spec,true);
const pending = [...seen];
const traversed = new Set();
while (pending.length) {
  const spec=pending.pop();
  if (traversed.has(spec)) continue;
  traversed.add(spec);
  const loc=new URL(spec,root);
  if (!loc.pathname.endsWith('.js') || loc.pathname.includes('/vendor/')) continue;
  const code=await readFile(loc,'utf8');
  for (const m of code.matchAll(/(?:from\s*|import\s*\(?\s*|new URL\(\s*)['"](\.[./][^'"]+\.(?:js|mjs|json)(?:\?[^'"]*)?)['"]/g)) {
    const found=local(m[1],loc); seen.add(found); pending.push(found);
  }
}
for (const p of catalogPacks) if (p.url) seen.add(local(p.url));
for (const p of ['./assets/sources/magna-carta-1215.jpg','./assets/logos/paideia-192.png','./assets/logos/scriptorium-192.png','./assets/icons/icon-512.png','./assets/logos/athenaeum-inverse.svg?v=14r1']) seen.add(p);
const release = JSON.parse(await readFile(new URL('version.json',root),'utf8')).version;
const entry = [...initial].find(path => path.startsWith('./academy/app.js?v='));
if (!entry) throw new Error('De app-entry mist een cacheversie.');
const version = release + '-' + new URL(entry,root).searchParams.get('v');
const pdf = [...seen].filter(p=>/pdf[^/]*\.mjs|jszip/.test(p));
const all = [...seen].filter(p=>!pdf.includes(p)).sort();
for (const spec of [...all,...pdf]) {
  const url=new URL(spec,root);
  if (!url.pathname.endsWith('/')) await readFile(url);
}
const output = '// Generated by scripts/build-offline.mjs\nself.learningAssets = '+JSON.stringify({version,initial:[...initial].sort(),all,extra:pdf},null,2)+';\n';
await writeFile(new URL('sw-assets.js',root),output);
