// Run with Node after editing lesson metadata. Lesson texts stay in their own packs.
import { readFile, writeFile } from 'node:fs/promises';
import { catalogPacks } from '../academy/catalog-packs.js';

const index = {};
const ids = new Set();
for (const pack of catalogPacks) {
  const lessons = pack.url ? JSON.parse(await readFile(pack.url, 'utf8')) : await pack.load();
  index[pack.key] = lessons.map(lesson => {
    if (!lesson.id || !lesson.title || !lesson.items?.length || ids.has(lesson.id)) {
      throw new Error('Invalid or duplicate lesson in ' + pack.key + ': ' + lesson.id);
    }
    ids.add(lesson.id);
    const row = [lesson.id, lesson.track, lesson.title, lesson.items.length, lesson.level || '', lesson.extension || ''];
    if (lesson.anchor) row.push(lesson.anchor);
    return row;
  });
}
const lines = Object.entries(index).map(([key, rows]) => '  ' + JSON.stringify(key) + ': [\n' +
  rows.map(row => '    ' + JSON.stringify(row)).join(',\n') + '\n  ]');
const output = '// Generated by scripts/build-catalog.mjs\nexport const catalogIndex = {\n' + lines.join(',\n') + '\n};\n';
await writeFile(new URL('../academy/catalog-index.js', import.meta.url), output);
